const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

interface CachedSource {
  readonly source: SourceGroup
  readonly raw: Buffer
}

interface CoordinatePoint { readonly lon: number; readonly lat: number }

function usage(): never {
  throw new Error('Usage: node --experimental-strip-types scripts/city/build-city.ts <city-id> [--check] | --check-batch <city-id>...')
}

function parseArguments(): { readonly cityIds: readonly string[]; readonly check: boolean; readonly batch: boolean } {
  const args = process.argv.slice(2)
  const batch = args.includes('--check-batch')
  const check = args.includes('--check') || batch
  const unknown = args.filter(arg => arg !== '--check' && arg !== '--check-batch' && arg.startsWith('-'))
  const cityIds = args.filter(arg => !arg.startsWith('-'))
  if (unknown.length || !cityIds.length || (batch ? args.includes('--check') : cityIds.length !== 1)) return usage()
  for (const cityId of cityIds) if (!SLUG.test(cityId)) throw new Error('City id must be a lowercase slug')
  return { cityIds, check, batch }
}

async function moduleAt(path: string): Promise<Record<string, unknown>> {
  const namespace: unknown = await import(pathToFileURL(path).href)
  if (!isRecord(namespace)) throw new TypeError(`${relative(root, path)} did not export a module namespace`)
  return namespace
}

const unionText = (values: readonly string[]): string => values.map(value => JSON.stringify(value)).join(' | ')

function legacyRulesText(recipe: LegacyCityRecipe): string {
  const names = recipe.exports
  const localUnitType = `${names.typePrefix}LocalGovernmentId`
  const districtType = `${names.typePrefix}DistrictId`
  const hubType = `${names.typePrefix}HubId`
  const seeds = JSON.stringify(recipe.rules.localUnits)
  return [
    `// ${GENERATED}`,
    `import type { CityModuleRules, LgaDefinition } from '../../../types/content.ts'`,
    `import { OGUN_RULES_BASE } from '../ogun/rules.ts'`,
    `import { SAGAMU_LEGACY_RECIPE } from './recipe.ts'`,
    '',
    `export type ${localUnitType} = ${unionText(recipe.rules.localUnits.map(unit => unit.id))}`,
    `export type ${districtType} = ${unionText(recipe.rules.districts.map(district => district.id))}`,
    `export type ${hubType} = ${unionText(recipe.rules.hubs.map(hub => hub.id))}`,
    `type Seed = Omit<LgaDefinition, 'id' | 'districts' | 'beta'> & { id: ${localUnitType}; districts?: ${districtType}[] }`,
    `const seeds = ${seeds} satisfies Seed[]`,
    '',
    `export const ${names.localUnits} = Object.freeze(seeds.map(unit => Object.freeze({ beta: true as const, districts: [], ...unit })))`,
    `export const ${names.mapOrigin} = Object.freeze({ ...SAGAMU_LEGACY_RECIPE.rules.mapOrigin })`,
    `const legacy = SAGAMU_LEGACY_RECIPE.rules`,
    '',
    `export const ${names.rules} = Object.freeze({`,
    `  ...OGUN_RULES_BASE,`,
    `  id: SAGAMU_LEGACY_RECIPE.id, name: legacy.name, units: ${names.localUnits},`,
    `  hub: legacy.hub,`,
    `  rentedHomeIds: legacy.rentedHomeIds, defaultRentedHome: legacy.defaultRentedHome,`,
    `  atlas: legacy.atlas,`,
    `  mapOrigin: ${names.mapOrigin},`,
    `  districts: legacy.districts,`,
    `  hubs: legacy.hubs,`,
    `  links: legacy.links,`,
    `} satisfies CityModuleRules<'${recipe.id}', 'ogun', ${localUnitType}, ${districtType}, ${hubType}>)`,
    '',
  ].join('\n')
}

function legacyContentText(recipe: LegacyCityRecipe): string {
  return `// ${GENERATED}\nimport { buildOgunContent } from '../ogun/contentBuilder.ts'\nimport { SAGAMU_LEGACY_RECIPE } from './recipe.ts'\n\nexport const ${recipe.exports.content} = buildOgunContent(SAGAMU_LEGACY_RECIPE.content)\n`
}

function legacyMapText(recipe: LegacyCityRecipe): string {
  const names = recipe.exports
  const localUnitType = `${names.typePrefix}LocalGovernmentId`
  return `// ${GENERATED}\nimport type { CityMapPack } from '../../../types/content.ts'\nimport { OGUN_CITY_LGA_IDS } from '../../../map3d/geo/data/ogun.ts'\nimport { ${recipe.map.landmarksExport} } from '../ogun/landmarks.ts'\nimport { ogunCityGeometry, ogunStateOverview } from '../ogun/mapOverview.ts'\nimport { ogunScene } from '../ogun/scene.ts'\nimport { ${names.mapOrigin} } from './rules.ts'\nimport type { ${localUnitType} } from './rules.ts'\n\nexport const ${names.map}: CityMapPack<'${recipe.id}', ${localUnitType}> = Object.freeze({\n  cityId: '${recipe.id}', origin: ${names.mapOrigin}, projection: 'nigeria-equirectangular-v1', unitsPerKm: 10,\n  localUnitIds: OGUN_CITY_LGA_IDS['${recipe.id}'], stateFeatureId: '${recipe.map.stateFeatureId}',\n  loadScene: async () => {\n    const [{ ${names.city} }, { createModulePack }] = await Promise.all([import('./index.ts'), import('../../../map3d/cities/module.ts')])\n    return createModulePack(${names.city}, ogunScene('${recipe.id}', ${recipe.map.landmarksExport}))\n  },\n  loadGeometry: async () => ogunCityGeometry(OGUN_CITY_LGA_IDS['${recipe.id}']),\n  loadStateOverview: async () => ogunStateOverview(),\n})\n`
}

function legacyIndexText(recipe: LegacyCityRecipe): string {
  const names = recipe.exports
  const prefix = names.typePrefix
  return `// ${GENERATED}\nimport type { CityModule } from '../../../types/content.ts'\nimport { ${names.rules} } from './rules.ts'\nimport type { ${prefix}DistrictId, ${prefix}HubId, ${prefix}LocalGovernmentId } from './rules.ts'\n\nexport const ${names.city} = Object.freeze({\n  id: '${recipe.id}', rules: ${names.rules},\n  loadContent: async () => (await import('./content.ts')).${names.content},\n  loadMap: async () => (await import('#city-map/${recipe.id}')).${names.map},\n} satisfies CityModule<'${recipe.id}', 'ogun', ${prefix}LocalGovernmentId, ${prefix}DistrictId, ${prefix}HubId>)\n\nexport { ${names.localUnits}, ${names.mapOrigin}, ${names.rules} } from './rules.ts'\n`
}

export function legacyGeneratedFiles(recipe: LegacyCityRecipe): Readonly<Record<'rules.ts' | 'content.ts' | 'map.ts' | 'index.ts', string>> {
  return Object.freeze({
    'rules.ts': legacyRulesText(recipe),
    'content.ts': legacyContentText(recipe),
    'map.ts': legacyMapText(recipe),
    'index.ts': legacyIndexText(recipe),
  })
}

async function verifyLegacy(cityId: string, recipePath: string, check: boolean): Promise<boolean> {
  const namespace = await moduleAt(recipePath)
  const recipes = Object.values(namespace).filter(isDefinedLegacyCityRecipe)
  if (recipes.length !== 1) throw new Error(`${relative(root, recipePath)} must export exactly one defined legacy city recipe`)
  const recipe = recipes[0]!
  if (recipe.id !== cityId) throw new Error(`${relative(root, recipePath)} preserves ${recipe.id}, not ${cityId}`)
  const cityDirectory = dirname(recipePath)
  const outputs = Object.entries(legacyGeneratedFiles(recipe)).map(([file, output]) => [join(cityDirectory, file), output] as const)
  let stale = false
  for (const [path, output] of outputs) stale = writeGenerated(path, output, check, true) || stale
  if (check && stale) {
    process.exitCode = 1
    return false
  }
  const text = JSON.stringify(await recipe.loadSnapshot())
  const bytes = Buffer.byteLength(text)
  const sha256 = createHash('sha256').update(text).digest('hex')
  if (bytes !== recipe.baselineBytes || sha256 !== recipe.baselineSha256) {
    throw new Error(`${cityId}: legacy runtime differs from its pinned baseline; expected ${recipe.baselineBytes} bytes ${recipe.baselineSha256}, received ${bytes} bytes ${sha256}`)
  }
  console.log(`${cityId}: legacy rules, content and geometry match ${bytes} baseline bytes (${sha256}).`)
  return true
}

function cachePath(source: SourceGroup): string {
  const cache = source.cache
  const path = resolve(root, cache.path)
  const fromRoot = relative(root, path)
  if (!fromRoot || fromRoot.startsWith('..') || isAbsolute(fromRoot)) throw new Error(`${source.id}: cache path leaves the repository`)
  return path
}

function verifyCaches(spec: CitySpec): ReadonlyMap<string, CachedSource> {
  const checked = new Map<string, CachedSource>()
  for (const source of spec.sourceGroups) {
    const path = cachePath(source)
    if (!existsSync(path) || !statSync(path).isFile()) throw new Error(`${source.id}: pinned cache is missing at ${relative(root, path)}`)
    const raw = readFileSync(path)
    const sha256 = createHash('sha256').update(raw).digest('hex')
    if (raw.length !== source.cache.bytes || sha256 !== source.cache.sha256) {
      throw new Error(`${source.id}: pinned cache does not match ${source.cache.bytes} bytes and SHA-256 ${source.cache.sha256}`)
    }
    checked.set(source.id, { source, raw })
  }
  return checked
}

function finitePoint(value: unknown): CoordinatePoint | null {
  if (!isRecord(value) || typeof value.lon !== 'number' || !Number.isFinite(value.lon) || typeof value.lat !== 'number' || !Number.isFinite(value.lat)) return null
  return { lon: value.lon, lat: value.lat }
}

function osmCoordinate(value: unknown, reference: Extract<CoordinateReference, { provider: 'openstreetmap' }>): CoordinatePoint | null {
  if (!isRecord(value) || !Array.isArray(value.elements)) return null
  for (const element of value.elements) {
    if (!isRecord(element) || element.type !== reference.element || element.id !== reference.id) continue
    const direct = finitePoint(element)
    if (direct) return direct
    const centre = finitePoint(element.center)
    if (centre) return centre
  }
  return null
}

export function wikidataCoordinate(value: unknown, reference: Extract<CoordinateReference, { provider: 'wikidata' }>): CoordinatePoint | null {
  if (!isRecord(value) || !isRecord(value.entities)) return null
  const entity = value.entities[reference.entity]
  if (!isRecord(entity) || !isRecord(entity.claims) || !Array.isArray(entity.claims.P625)) return null
  for (const claim of entity.claims.P625) {
    if (!isRecord(claim) || !isRecord(claim.mainsnak) || !isRecord(claim.mainsnak.datavalue)) continue
    const coordinate = claim.mainsnak.datavalue.value
    if (!isRecord(coordinate)
      || typeof coordinate.longitude !== 'number' || !Number.isFinite(coordinate.longitude) || Math.abs(coordinate.longitude) > 180
      || typeof coordinate.latitude !== 'number' || !Number.isFinite(coordinate.latitude) || Math.abs(coordinate.latitude) > 90) continue
    return { lon: coordinate.longitude, lat: coordinate.latitude }
  }
  return null
}

function coordinateFromCache(cache: CachedSource, reference: CoordinateReference, label: string): CoordinatePoint {
  let parsed: unknown
  try {
    parsed = JSON.parse(cache.raw.toString('utf8'))
  } catch {
    throw new TypeError(`${label}: coordinate cache ${cache.source.id} is not JSON`)
  }
  const point = reference.provider === 'openstreetmap'
    ? osmCoordinate(parsed, reference)
    : wikidataCoordinate(parsed, reference)
  if (!point) {
    const identity = reference.provider === 'openstreetmap' ? `${reference.element}/${reference.id}` : reference.entity
    throw new Error(`${label}: ${identity} is absent from coordinate cache ${cache.source.id}`)
  }
  return point
}

function verifyCoordinate(
  label: string,
  expected: CoordinatePoint,
  sourceId: string,
  reference: CoordinateReference,
  caches: ReadonlyMap<string, CachedSource>,
): void {
  const cache = caches.get(sourceId)
  if (!cache) throw new Error(`${label}: coordinate source ${sourceId} has no verified cache`)
  const actual = coordinateFromCache(cache, reference, label)
  const difference = Math.max(Math.abs(actual.lon - expected.lon), Math.abs(actual.lat - expected.lat))
  if (difference > 0.000001) throw new Error(`${label}: coordinate differs from ${sourceId} by ${difference} degrees`)
}

function verifyCoordinates(spec: CitySpec, caches: ReadonlyMap<string, CachedSource>): void {
  verifyCoordinate('atlas', spec.atlas, spec.atlas.coordinateSourceId, spec.atlas.coordinateRef, caches)
  for (const place of spec.places) verifyCoordinate(place.id, place, place.coordinateSourceId, place.coordinateRef, caches)
}

