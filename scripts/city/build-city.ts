/** What the content builder reads of a regular: no place id and no list of source facts. */
export function personSeedOf(entry: CastEntry): CityPersonSeed {
  return {
    name: entry.name,
    role: entry.role,
    quotes: entry.quotes,
    ...(entry.age ? { age: entry.age } : {}),
    ...(entry.greeting ? { greeting: entry.greeting } : {}),
    ...(entry.look ? { look: entry.look } : {}),
    ...(entry.note ? { note: entry.note } : {}),
  }
}

/** Plain data written with bare keys, so the browser build can leave the `note:` fields out. */
function literalText(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(literalText).join(', ')}]`
  if (isRecord(value)) return `{ ${Object.entries(value).map(([key, item]) => `${/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)}: ${literalText(item)}`).join(', ')} }`
  return JSON.stringify(value)
}

export function formulaContentText(people: readonly CityPersonSeed[]): string {
  const written = people.length ? `[\n${people.map(person => `    ${literalText(person)},`).join('\n')}\n  ]` : '[]'
  return `// ${GENERATED}\nimport { buildFormulaContent } from '../formula/content.ts'\nimport { CITY_LOCAL_UNIT_ANCHORS, CITY_MAP_ORIGIN, CITY_PLAY_BOUNDS } from './geography.ts'\nimport { CITY_SCENES } from './scenes.ts'\nimport { CITY_SPEC } from './spec.ts'\n\nexport const CITY_CONTENT = buildFormulaContent({\n  spec: CITY_SPEC,\n  origin: CITY_MAP_ORIGIN,\n  bounds: CITY_PLAY_BOUNDS,\n  localUnitAnchors: CITY_LOCAL_UNIT_ANCHORS,\n  scenes: CITY_SCENES,\n  people: ${written},\n})\n`
}

export function formulaIndexText(cityId: string): string {
  return `// ${GENERATED}\nimport type { CityModule } from '../../../types/content.ts'\nimport { CITY_RULES } from './rules.ts'\nimport { CITY_SPEC } from './spec.ts'\n\nexport const city = Object.freeze({\n  id: CITY_SPEC.id,\n  rules: CITY_RULES,\n  loadContent: async () => (await import('./content.ts')).CITY_CONTENT,\n  loadMap: async () => (await import('#city-map/${cityId}')).CITY_MAP,\n} satisfies CityModule<typeof CITY_SPEC.id>)\n`
}

function writeGenerated(path: string, text: string, check: boolean, allowAuthored = false): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false
  if (check) {
    console.error(`${relative(root, path)} is stale or missing`)
    return true
  }
  if (!allowAuthored && existsSync(path) && !readFileSync(path, 'utf8').includes(GENERATED)) {
    throw new Error(`${relative(root, path)} is hand-authored; refusing to overwrite it`)
  }
  mkdirSync(dirname(path), { recursive: true })
  const partial = `${path}.${process.pid}.part`
  writeFileSync(partial, text)
  renameSync(partial, path)
  return true
}

export const generatedTextIsCurrent = (path: string, text: string): boolean => existsSync(path) && readFileSync(path, 'utf8') === text

async function assertNoExistingCityOverlap(cityId: string, polygons: Parameters<typeof assertNoOpenCityGeometryOverlap>[0][number]['polygons']): Promise<void> {
  for (const city of CITY_CATALOGUE) {
    if (!city.open || city.id === cityId) continue
    const loader = CITY_LOADERS[city.id]
    if (!loader) throw new Error(`${city.id}: open catalogue entry has no loader`)
    const module = await loader()
    const geometry = await (await module.loadMap()).loadGeometry()
    const existingPolygons = geometry.playArea.map(polygon => polygon.map(ring => ring.map(([lon, lat]): [number, number] => [lon, lat])))
    assertNoOpenCityGeometryOverlap([
      { cityId, polygons },
      { cityId: city.id, polygons: existingPolygons },
    ])
  }
}

/** Two regulars at every place: the city's authored cast.ts where it has one, a generated pair everywhere else. */
export async function castOf(cityDirectory: string, spec: CitySpec): Promise<readonly CastEntry[]> {
  const castPath = join(cityDirectory, 'cast.ts')
  const authored: unknown = existsSync(castPath) ? (await moduleAt(castPath))['CITY_CAST'] : []
  if (!Array.isArray(authored)) throw new TypeError(`${relative(root, castPath)} must export CITY_CAST as an array`)
  const entries: readonly CastEntry[] = authored
  const errors = validateCast(spec, entries)
  if (errors.length) throw new Error(`${spec.id} cast is invalid:\n- ${errors.join('\n- ')}`)
  return castFor(spec, orderedPlacesOf(spec), entries)
}

async function buildFormula(cityId: string, specPath: string, check: boolean): Promise<boolean> {
  const namespace = await moduleAt(specPath)
  const specs = Object.values(namespace).filter(isDefinedCitySpec)
  if (specs.length !== 1) throw new Error(`${relative(root, specPath)} must export exactly one value created by defineCitySpec`)
  const spec = specs[0]!
  if (spec.id !== cityId) throw new Error(`${relative(root, specPath)} defines ${spec.id}, not ${cityId}`)
  const caches = verifyCaches(spec)
  verifyCoordinates(spec, caches)
  const geometry = await buildCityGeometry({
    cityId: spec.id,
    stateId: spec.state.id,
    stateSourceName: spec.state.sourceName,
    localUnits: spec.localUnits.map(unit => ({ id: unit.id, sourceName: unit.sourceName, name: unit.name })),
    atlas: spec.atlas,
    ...(spec.origin ? { origin: spec.origin } : {}),
    venues: spec.places.map(place => ({ id: place.id, name: place.name, lon: place.lon, lat: place.lat, localUnitId: place.localUnitId })),
    surface: { sha256: spec.geometry.surface.sha256, bytes: spec.geometry.surface.bytes },
    offline: check,
  })
  await assertNoExistingCityOverlap(cityId, geometry.playAreaPolygons)

  const cityDirectory = join(root, 'src', 'game', 'cities', cityId)
  const people = (await castOf(cityDirectory, spec)).map(personSeedOf)
  const outputs: readonly (readonly [string, string])[] = [
    [join(cityDirectory, 'rules.ts'), formulaRulesText()],
    [join(cityDirectory, 'scenes.ts'), formulaScenesText()],
    [join(cityDirectory, 'content.ts'), formulaContentText(people)],
    [join(cityDirectory, 'geography.ts'), geometry.geographyModuleText],
    [join(cityDirectory, 'map.ts'), geometry.runtimeModuleText],
    [join(cityDirectory, 'index.ts'), formulaIndexText(cityId)],
    [join(root, 'src', 'map3d', 'geo', 'data', `${cityId}.formula.ts`), geometry.dataModuleText],
  ]
  let stale = false
  for (const [path, text] of outputs) stale = writeGenerated(path, text, check) || stale
  if (check && stale) {
    process.exitCode = 1
    return false
  }
  console.log(`${cityId}: ${check ? 'generated modules match' : 'generated seven modules'}; ${spec.places.length} sourced places, ${spec.localUnits.length} local units.`)
  return true
}

function runCatalogue(check: boolean): void {
  const script = join(root, 'scripts', 'city', 'build-catalogue.ts')
  const result = spawnSync(process.execPath, ['--experimental-strip-types', script, ...(check ? ['--check'] : [])], {
    cwd: root,
    stdio: 'inherit',
  })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`City catalogue ${check ? 'check' : 'generation'} failed with status ${result.status ?? 'unknown'}`)
}

async function verifyCity(cityId: string, check: boolean): Promise<boolean> {
  const cityDirectory = join(root, 'src', 'game', 'cities', cityId)
  const recipePath = join(cityDirectory, 'recipe.ts')
  if (existsSync(recipePath)) return verifyLegacy(cityId, recipePath, check)
  const specPath = join(cityDirectory, 'spec.ts')
  if (!existsSync(specPath)) throw new Error(`${relative(root, specPath)} is missing`)
  return buildFormula(cityId, specPath, check)
}

async function main(): Promise<void> {
  const { cityIds, check, batch } = parseArguments()
  if (!batch) {
    if (await verifyCity(cityIds[0]!, check)) runCatalogue(check)
    return
  }

  let failed = false
  for (const cityId of cityIds) {
    try {
      if (!await verifyCity(cityId, true)) failed = true
    } catch (error) {
      console.error(`${cityId}: ${error instanceof Error ? error.message : String(error)}`)
      failed = true
    }
  }
  try {
    // The catalogue is global, so validate it once after every requested city.
    runCatalogue(true)
    console.log('Batch catalogue check passed.')
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    failed = true
  }
  if (failed) process.exitCode = 1
}

const entry = process.argv[1]
if (entry && import.meta.url === pathToFileURL(resolve(entry)).href) await main()
